//! # Default Asset Converter
//!
//! This crate is a very small crate whose only function is to convert default assets into easily
//! deserializable representations of themselves, and put them in easily accessible places for the
//! project
#![warn(missing_docs)]

use std::path::PathBuf;

#[cfg(feature = "animations")]
#[allow(unused)]
use strum_macros::Display;

#[cfg(feature = "animations")]
#[allow(unused)]
use strum_macros::EnumString;

#[cfg(feature = "animations")]
#[allow(unused)]
use uuid::Uuid;

/// Returns the path to the generated default asets dir
pub fn default_assets() -> PathBuf {
    PathBuf::from(env!("BENTHIC_DEFAULT_ASSETS"))
}

/// builds the default skeleton constant
pub mod generated {
    use benthic_protocol::avatar::skeleton::Skeleton;
    use once_cell::sync::Lazy;

    /// Default skeleton constant used throughout the project.
    /// This reads the default_skeleton.json generated by build.rs and turns it into a constant that can be used in line
    pub static DEFAULT_SKELETON: Lazy<Skeleton> = Lazy::new(|| {
        serde_json::from_str(include_str!(concat!(
            env!("OUT_DIR"),
            "/default_skeleton.json"
        )))
        .expect("Failed to deserialize default skeleton")
    });
}

/// Path to the default generated assets
pub fn generated_asset_path() -> PathBuf {
    PathBuf::from(env!("OUT_DIR"))
}

/// Path to the default generated animations
pub fn generated_animation_path() -> PathBuf {
    PathBuf::from(env!("OUT_DIR")).join("Animations")
}

/// Path to the benthic default texture
pub fn default_texture_path() -> PathBuf {
    PathBuf::from(concat!(env!("OUT_DIR"), "/default.png"))
}

/// Path to the benthic invisible mesh
/// Used to ensure the UI always has something to render when parent objects fail to load in
pub fn no_geometry_mesh_path() -> PathBuf {
    PathBuf::from(concat!(env!("OUT_DIR"), "/empty.glb"))
}

#[cfg(feature = "animations")]
#[allow(unused)]
macro_rules! define_animations {
    (
        $( $name:ident => $uuid:expr ),* $(,)?
    ) => {

        pub mod animations {
            $(
                pub mod $name {
                    include!(concat!(
                        env!("OUT_DIR"),
                        "/",
                        stringify!($name),
                        ".json"
                    ));
                }
            )*
        }
        pub fn joints(&self) -> &'static [Joint] {
            match self {
                $(
                    Self::$name => &crate::generated::animations::$name::JOINTS,
                )*
            }
        }
    };
}
